"""pwninit-lite: make a challenge binary run against the libc it shipped with.

Identifies the supplied libc, finds or names the matching loader, and makes
the binary use them -- with patchelf when it is installed, and with a loader
wrapper script when it is not (which needs no patching at all).

    pwninit-lite ./vuln --libc ./libc.so.6
    pwninit-lite ./vuln --libc ./libc.so.6 --ld ./ld-2.31.so -o ./vuln_patched
"""

from __future__ import annotations

import os
import re
import shutil
import stat
import subprocess
import sys

from ctftools.core import term
from ctftools.core.binary import load_binary
from ctftools.core.cliutil import add_common_args, apply_output_flags, base_parser, fail, resolve_binary
from ctftools.core.report import Report
from ctftools.core.runner import run_target

VERSION_RE = re.compile(rb"GNU C Library[^\0]*?release version (\d+\.\d+)")
UBUNTU_RE = re.compile(rb"(GLIBC|glibc)[ -](\d+\.\d+)[^\0]{0,40}?(ubuntu|Ubuntu|deb|Debian)[^\0]{0,30}")

WRAPPER = """\
#!/bin/sh
# Generated by ctftools pwninit-lite.
# Runs the challenge binary against its own libc without patching it.
exec {loader} --library-path {libdir} {binary} "$@"
"""


def libc_version(path: str) -> tuple[str | None, str]:
    """The glibc version string inside a libc.so.6."""
    with open(path, "rb") as fh:
        data = fh.read()
    match = VERSION_RE.search(data)
    version = match.group(1).decode() if match else None

    detail = ""
    banner = re.search(rb"GNU C Library[^\0]{0,120}", data)
    if banner:
        detail = banner.group(0).decode("latin-1", "replace").strip()
    return version, detail


def find_loader(libc_path: str, version: str | None) -> str | None:
    """A loader sitting next to the libc, or one matching its version."""
    directory = os.path.dirname(os.path.abspath(libc_path)) or "."
    candidates = []
    for name in sorted(os.listdir(directory)):
        if name.startswith("ld-") or name.startswith("ld-linux"):
            candidates.append(os.path.join(directory, name))
    if candidates:
        if version:
            exact = [c for c in candidates if version in os.path.basename(c)]
            if exact:
                return exact[0]
        return candidates[0]
    if version:
        system = f"/lib/x86_64-linux-gnu/ld-{version}.so"
        if os.path.exists(system):
            return system
    return None


def patch_with_patchelf(binary: str, libc: str, loader: str, output: str) -> tuple[bool, str]:
    """Use patchelf to set the interpreter and rpath."""
    if shutil.which("patchelf") is None:
        return False, "patchelf is not installed"

    shutil.copy2(binary, output)
    os.chmod(output, os.stat(output).st_mode | stat.S_IXUSR)
    libdir = os.path.dirname(os.path.abspath(libc)) or "."
    try:
        subprocess.run(["patchelf", "--set-interpreter", os.path.abspath(loader), output],
                       check=True, capture_output=True)
        subprocess.run(["patchelf", "--set-rpath", libdir, output],
                       check=True, capture_output=True)
    except subprocess.CalledProcessError as exc:
        return False, (exc.stderr or b"").decode().strip() or "patchelf failed"
    return True, f"patched with patchelf: interpreter {loader}, rpath {libdir}"


def patch_in_place(binary: str, loader: str, output: str) -> tuple[bool, str]:
    """Rewrite PT_INTERP in place, which only works if the new path is no longer."""
    from pwnlib.elf import ELF

    elf = ELF(binary, checksec=False)
    segment = None
    for candidate in elf.iter_segments():
        if candidate.header["p_type"] == "PT_INTERP":
            segment = candidate
            break
    if segment is None:
        return False, "the binary has no PT_INTERP segment (statically linked?)"

    current = segment.data().rstrip(b"\x00")
    new = os.path.abspath(loader).encode()
    if len(new) > len(current):
        return False, (
            f"the new loader path is {len(new)} bytes and the slot holds {len(current)}; "
            "in-place patching cannot grow it, so use the wrapper script or install patchelf"
        )

    with open(binary, "rb") as fh:
        data = bytearray(fh.read())
    offset = segment.header["p_offset"]
    data[offset:offset + len(current) + 1] = new + b"\x00" * (len(current) + 1 - len(new))
    with open(output, "wb") as fh:
        fh.write(data)
    os.chmod(output, os.stat(binary).st_mode | stat.S_IXUSR)
    return True, f"PT_INTERP rewritten in place to {new.decode()}"


def write_wrapper(binary: str, libc: str, loader: str, output: str) -> tuple[bool, str]:
    """A shell script that invokes the loader directly: no patching needed."""
    script = output if output.endswith(".sh") else output + ".sh"
    libdir = os.path.dirname(os.path.abspath(libc)) or "."
    with open(script, "w") as fh:
        fh.write(WRAPPER.format(
            loader=os.path.abspath(loader),
            libdir=libdir,
            binary=os.path.abspath(binary),
        ))
    os.chmod(script, 0o755)
    return True, f"wrapper written to {script}"


def verify(path: str, libc: str, timeout: float = 5.0) -> tuple[bool, str]:
    """Run the result and check it loaded the libc we meant."""
    result = run_target(path, b"\n", timeout=timeout)
    if result.timed_out:
        return True, "it started and waited for input (timed out, which is fine)"
    if result.returncode == 127 or b"No such file" in result.stderr:
        return False, (result.stderr.strip() or b"loader not found").decode("latin-1", "replace")[:160]
    if b"version `GLIBC" in result.stderr:
        return False, result.stderr.strip().decode("latin-1", "replace")[:160]
    return True, f"it ran and exited with {result.classify()}"


def prepare(binary: str, libc: str, loader: str | None = None, output: str | None = None,
            method: str = "auto", check: bool = True) -> Report:
    info = load_binary(binary)
    report = Report(tool="pwninit-lite", target=binary)

    version, banner = libc_version(libc)
    loader = loader or find_loader(libc, version)
    output = output or (binary + "_patched")

    report.data.update({
        "libc": os.path.abspath(libc),
        "libc_version": version,
        "libc_banner": banner,
        "loader": os.path.abspath(loader) if loader else None,
        "output": os.path.abspath(output),
    })

    sec = report.section("Challenge libc")
    sec.add(term.table([
        ["libc", os.path.basename(libc)],
        ["version", version or term.warn("unknown")],
        ["loader", os.path.basename(loader) if loader else term.bad("not found")],
        ["binary interpreter", info.interpreter or term.dim("none (static)")],
    ]))
    if banner:
        sec.add("")
        sec.add("  " + term.dim(banner[:120]))

    if loader is None:
        report.warn(
            f"no loader next to the libc. A libc {version or '?'} binary needs the matching "
            f"ld-{version or 'X.YZ'}.so: take it from the challenge files, or from the "
            "Ubuntu/Debian package that ships this libc"
        )
        report.data["ready"] = False
        return report

    results = []
    if method in ("auto", "patchelf"):
        ok, detail = patch_with_patchelf(binary, libc, loader, output)
        results.append(("patchelf", ok, detail))
        if ok:
            method = "patchelf"
    if method in ("auto", "inplace") and not any(r[1] for r in results):
        ok, detail = patch_in_place(binary, loader, output)
        results.append(("in-place PT_INTERP", ok, detail))
        if ok:
            method = "inplace"
    if method in ("auto", "wrapper") and not any(r[1] for r in results):
        ok, detail = write_wrapper(binary, libc, loader, output)
        results.append(("wrapper script", ok, detail))
        if ok:
            method = "wrapper"

    applied = report.section("What was done")
    for name, ok, detail in results:
        applied.add(f"  {term.good('done') if ok else term.dim('skipped')}  {name}: {detail}")

    succeeded = [r for r in results if r[1]]
    report.data["method"] = method if succeeded else None
    report.data["ready"] = bool(succeeded)

    if succeeded and check:
        runnable = output + ".sh" if method == "wrapper" and not output.endswith(".sh") else output
        ok, detail = verify(runnable, libc)
        report.data["verified"] = ok
        verification = report.section("Check")
        verification.add("  " + (term.good("runs") if ok else term.bad("does not run")) + f"  {detail}")
        verification.add("")
        verification.add(f"  {term.dim('use it with:')} {runnable}")
        verification.add(f"  {term.dim('in a script:')} process([{runnable!r}])")

    if version:
        report.note(f"with libc {version} identified, pass --libc {os.path.basename(libc)} "
                    "to ropchain --system to resolve system() and /bin/sh")
    return report


def build_parser():
    parser = base_parser("pwninit-lite", "Make a binary run against the challenge libc.")
    parser.add_argument("binary", help="the challenge binary")
    parser.add_argument("--libc", required=True, help="the libc.so.6 that shipped with it")
    parser.add_argument("--ld", dest="loader", help="the matching loader (found automatically if next to the libc)")
    parser.add_argument("-o", "--output", help="where to write the result (default: <binary>_patched)")
    parser.add_argument("--method", choices=["auto", "patchelf", "inplace", "wrapper"], default="auto",
                        help="how to do it (default: auto, best available)")
    parser.add_argument("--no-check", action="store_true", help="do not run the result afterwards")
    add_common_args(parser)
    return parser


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    apply_output_flags(args)
    if not os.path.exists(args.libc):
        fail(f"no such libc: {args.libc}")
    report = prepare(
        resolve_binary(args.binary), args.libc, loader=args.loader,
        output=args.output, method=args.method, check=not args.no_check,
    )
    report.emit(as_json=args.json)
    return 0 if report.data.get("ready") else 1


if __name__ == "__main__":
    sys.exit(main())
